# 提示词注册表：模块名 -> 任务专用系统提示词
TASK_PROMPTS = {
    "coding": CODING_SYSTEM,
    "coding_explain": CODING_EXPLAIN_SYSTEM,
    "doc_qa": DOC_QA_SYSTEM,
    "math_modeling": MATH_MODELING_SYSTEM,
    "benchmark": BENCHMARK_NUMERIC_SYSTEM,
}


def system_prompt(task_name, task_prompt=True):
    """根据任务名与消融开关选择系统提示词。"""
    if not task_prompt:
        return GENERIC_FINANCE_SYSTEM
    return TASK_PROMPTS.get(task_name, GENERIC_FINANCE_SYSTEM)
